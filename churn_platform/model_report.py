"""Write reports/phase3_model_evaluation.md from the computed results.

Like findings.py, every number is inserted from results, and comparative
sentences are chosen by the data (e.g. "no meaningful difference" only when
the gap is smaller than the fold-to-fold standard deviation).
"""

from collections import Counter

LABELS = {"dummy_most_frequent": "Dummy (most frequent)", "logreg": "LogReg",
          "logreg_balanced": "LogReg, balanced weights", "logreg_zero_fill": "LogReg, zero-fill",
          "sensitivity_logreg_without_tenure_totalcharges": "LogReg without tenure & TotalCharges"}


def _f(x, nd=3):
    return "n/a" if x is None else f"{x:.{nd}f}"


def _pct(x):
    return f"{100 * x:.1f}%"


def write_model_report(r: dict, path) -> None:
    s, test, train = r["split"], r["test_metrics"], r["train_metrics"]
    cv = {row["model"]: row for row in r["cv_results"]}
    ov, pipe = r["train_test_profile_overlap"], r["pipeline"]
    blank = r["blank_total_charges_rows"]
    dummy, lr, lrb = test["dummy_most_frequent"], test["logreg"], test["logreg_balanced"]

    lines = [
        "# Phase 3: baseline and logistic regression evaluation",
        "",
        f"_Generated by `python -m churn_platform.train_baseline` (raw SHA-256 `{r['raw_file_sha256'][:16]}…`, "
        f"scikit-learn {r['environment']['scikit-learn']}, pandas {r['environment']['pandas']}, "
        f"Python {r['environment']['python']}). Do not edit by hand._",
        "",
        "## 1. Problem definition and an important caveat",
        "",
        "- **Target:** `Churn` (Yes = 1, No = 0). **Predictors:** 19 columns, which is every column except "
        "`customerID` (an identifier) and the target.",
        "- **This is a retrospective, cross-sectional exercise.** All columns were recorded at the same "
        "moment as the outcome. For a customer who already churned, `tenure` is *how long they stayed before "
        "leaving* and `TotalCharges` is their *final* bill, so both partly describe the churn itself. A "
        "deployable early-warning model would need features frozen at a prediction date and churn observed in "
        "a *later* window. These scores measure how well the features separate churners from non-churners in "
        "this snapshot. They are **not** a forecast of real-world performance.",
        f"- To size this effect, a model **without `tenure` and `TotalCharges`** was cross-validated: ROC-AUC "
        f"{_f(cv['sensitivity_logreg_without_tenure_totalcharges']['roc_auc_mean'])} vs "
        f"{_f(cv['logreg']['roc_auc_mean'])} with them (training-set CV only). So the other 17 features still "
        "separate the classes well. Which of them matter is not measured here; that is Phase 4. They aren't "
        "automatically safe either: a contract or payment method might also have changed shortly before a "
        "customer left, and the snapshot can't show that.",
        "",
        "## 2. Split and leakage controls",
        "",
        f"- Stratified 80/20 split, seed {s['seed']}: **train {s['train_rows']:,}** "
        f"(churn {_pct(s['train_churn_rate'])}), **test {s['test_rows']:,}** "
        f"(churn {_pct(s['test_churn_rate'])}). The split is saved to `data/processed/train_test_split.csv`.",
        "- No customerID appears in both sets.",
        "- All learned preprocessing (median imputer, scaler, one-hot categories) sits inside a scikit-learn "
        "`Pipeline`, fitted on training rows only. In cross-validation it is re-fitted within each fold.",
        f"- The imputation median for `TotalCharges` is ${pipe['train_median_TotalCharges_used_for_imputation']:,.3f}, "
        "the median of the **training set**. 19 raw columns become "
        f"{pipe['n_features_after_preprocessing']} model inputs: 3 scaled numeric columns, 1 missing indicator, "
        "and the one-hot categories.",
        "- Every choice in this report (imputation, class weights) was made with **5-fold CV on the training "
        "set**. The test set was scored once, after all choices were fixed.",
        "",
        "### Train/test profile overlap",
        "",
        f"{ov['test_rows_with_profile_in_train']} of {ov['test_rows']:,} test customers "
        f"({_pct(ov['share_of_test'])}) have a feature profile identical to at least one training customer. "
        f"For {ov['of_which_all_train_labels_agree']} the training labels agree; for "
        f"{ov['of_which_train_labels_differ_or_mixed']} they differ or are mixed. These are **different customers** "
        "(IDs are unique), so this is not same-customer leakage, and they were not removed. Excluding them from "
        f"the test set changes LogReg's test ROC-AUC from {_f(lr['roc_auc'], 4)} to "
        f"{_f(r['test_metrics_excluding_overlap_rows']['logreg']['roc_auc'], 4)}, so they don't inflate the score.",
        "",
        "## 3. The 11 blank `TotalCharges` values",
        "",
    ]
    contracts = Counter(b["Contract"] for b in blank)
    churned = sum(b["churned"] for b in blank)
    lines += [
        f"All {len(blank)} have tenure 0 and {churned} of them churned. Contracts: "
        + ", ".join(f"{k} {v}" for k, v in contracts.most_common())
        + f". {sum(b['split'] == 'train' for b in blank)} are in train and {sum(b['split'] == 'test' for b in blank)} in test.",
        "",
        "| Strategy | Assumption | CV ROC-AUC | CV PR-AUC |",
        "|---|---|---:|---:|",
        f"| **Median + missing indicator** (primary) | none about what the blank means; the indicator lets the model treat "
        f"those rows separately | {_f(cv['logreg']['roc_auc_mean'], 4)} ± {_f(cv['logreg']['roc_auc_std'], 4)} "
        f"| {_f(cv['logreg']['average_precision_mean'], 4)} |",
        f"| Zero-fill | a tenure-0 customer has been billed $0. Plausible but unconfirmed "
        f"| {_f(cv['logreg_zero_fill']['roc_auc_mean'], 4)} ± {_f(cv['logreg_zero_fill']['roc_auc_std'], 4)} "
        f"| {_f(cv['logreg_zero_fill']['average_precision_mean'], 4)} |",
        "",
    ]
    gap = abs(cv["logreg"]["roc_auc_mean"] - cv["logreg_zero_fill"]["roc_auc_mean"])
    lines += [
        (f"The difference ({gap:.4f}) is far smaller than the fold-to-fold spread ({cv['logreg']['roc_auc_std']:.4f}), "
         "so **the choice makes no measurable difference**, which is expected when only "
         f"{sum(b['split'] == 'train' for b in blank)} training rows are affected. The primary strategy was kept "
         "because it makes no assumption about what a blank means."
         if gap < cv["logreg"]["roc_auc_std"] else
         f"The difference ({gap:.4f}) exceeds the fold-to-fold spread; investigate before relying on either."),
        "",
        "## 4. Cross-validation on the training set (5 folds, same folds for every model)",
        "",
        "| Model | ROC-AUC | PR-AUC | Precision | Recall | F1 | Accuracy |",
        "|---|---:|---:|---:|---:|---:|---:|",
    ]
    for name, row in cv.items():
        lines.append(
            f"| {LABELS.get(name, name)} | {_f(row['roc_auc_mean'])} ± {_f(row['roc_auc_std'])} | "
            f"{_f(row['average_precision_mean'])} | {_f(row['precision_mean'])} | {_f(row['recall_mean'])} | "
            f"{_f(row['f1_mean'])} | {_f(row['accuracy_mean'])} |")
    lines += [
        "",
        "The Dummy model never predicts churn, so its precision is 0/0 (undefined, shown as 0) and its recall is 0.",
        "",
        "## 5. Test-set results (scored once, threshold fixed at 0.5)",
        "",
        "| Metric | Dummy | LogReg | LogReg balanced |",
        "|---|---:|---:|---:|",
    ]
    for key, label in [("accuracy", "Accuracy"), ("precision", "Precision (churn)"), ("recall", "Recall (churn)"),
                       ("f1", "F1 (churn)"), ("roc_auc", "ROC-AUC"), ("average_precision", "PR-AUC (average precision)"),
                       ("brier", "Brier score (lower = better)")]:
        lines.append(f"| {label} | {_f(dummy[key])}{' (undefined)' if key == 'precision' and not dummy['precision_defined'] else ''} "
                     f"| {_f(lr[key])} | {_f(lrb[key])} |")
    lines += ["", "**Confusion matrices** (rows = actual, columns = predicted):", ""]
    for name, m in test.items():
        cm = m["confusion_matrix"]
        lines.append(f"- {LABELS[name]}: TN {cm['tn']}, FP {cm['fp']}, FN {cm['fn']}, TP {cm['tp']} "
                     f"(flags {m['predicted_positives']} of {m['n']} customers; catches {cm['tp']} of {m['positives']} churners)")
    lines += [
        "",
        "![Confusion matrices](figures/phase3_confusion_matrices.png)",
        "",
        "![ROC and PR curves](figures/phase3_roc_pr_curves.png)",
        "",
        "<details><summary>Classification reports</summary>",
        "",
    ]
    for name, m in test.items():
        lines += [f"**{LABELS[name]}**", "", "```", m["classification_report_text"].rstrip(), "```", ""]
    lines += ["</details>", "", "## 6. Interpretation", ""]

    lines.append(
        f"- **Why accuracy is not enough:** the Dummy model scores {_pct(dummy['accuracy'])} accuracy while "
        f"catching **zero** churners. LogReg's {_pct(lr['accuracy'])} is only {100 * (lr['accuracy'] - dummy['accuracy']):.1f} "
        f"points better. The balanced model catches more churners ({lrb['confusion_matrix']['tp']} vs "
        f"{lr['confusion_matrix']['tp']}) yet has *lower* accuracy ({_pct(lrb['accuracy'])}), because it raises more false "
        "alarms. Accuracy rewards getting the majority class right, which is the cheap part.")
    lines.append(
        f"- **Ranking quality:** LogReg's test ROC-AUC is {_f(lr['roc_auc'])}. PR-AUC is {_f(lr['average_precision'])}, "
        f"against a no-skill level of {_pct(lr['positives'] / lr['n'])} (the churn rate). PR-AUC focuses on the minority "
        "class, so it is the stricter number here.")
    lines.append(
        f"- **Balanced weights vs unweighted:** test ROC-AUC {_f(lrb['roc_auc'])} vs {_f(lr['roc_auc'])}. The ranking of "
        "customers barely changes. What changes is *where 0.5 falls*: weighting pushes probabilities upward, "
        f"so at 0.5 recall rises ({_f(lr['recall'])} → {_f(lrb['recall'])}) and precision falls "
        f"({_f(lr['precision'])} → {_f(lrb['precision'])}). Its Brier score is worse ({_f(lrb['brier'])} vs "
        f"{_f(lr['brier'])}). Since the ranking is nearly identical, that points to less faithful probabilities. "
        "A proper calibration check is Phase 4. Which trade-off is better depends on the cost of a missed "
        "churner versus a wasted retention offer, which is the Phase 4 threshold decision. "
        "**Unweighted LogReg is the primary model.** This was decided before the test set was scored: weighting "
        "mostly moves the effective threshold, and the threshold should be chosen explicitly from costs.")
    train_gap = train["logreg"]["roc_auc"] - lr["roc_auc"]
    lines.append(
        f"- **Overfitting check:** LogReg ROC-AUC is {_f(train['logreg']['roc_auc'])} on train, "
        f"{_f(cv['logreg']['roc_auc_mean'])} in CV and {_f(lr['roc_auc'])} on test. "
        + ("The gap is small, so there is no sign of overfitting." if train_gap < 0.02 else
           f"The train–test gap of {train_gap:.3f} deserves attention."))
    lines += [
        "",
        "## 7. Limitations",
        "",
        "- Retrospective snapshot (see section 1). Real-world performance is unknown.",
        "- A single train/test split. A different seed would give somewhat different test numbers; the CV "
        "standard deviations give a sense of that spread.",
        "- `C` (regularisation strength) was left at the default 1.0 and not tuned. The 0.5 threshold is arbitrary. "
        "Both are Phase 4 topics.",
        "- Synthetic IBM data with label noise (customers with identical profiles but different outcomes).",
        "- Coefficients are not interpreted yet. Correlated one-hot columns make raw coefficients misleading, "
        "and interpretation is a Phase 4 topic.",
        "",
    ]
    path.write_text("\n".join(lines), encoding="utf-8")
