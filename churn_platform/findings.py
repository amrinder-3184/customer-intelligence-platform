"""Write reports/phase2_findings.md from computed results.

Every number in the report is inserted from the analysis results; nothing is
typed in by hand. Comparative sentences are generated only when the data
supports them (see _contract_internet_sentence), so re-running on different
data cannot produce a stale or false claim.
"""

import pandas as pd


def _pct(x: float) -> str:
    return f"{100 * x:.1f}%"


def _ci(row) -> str:
    return f"{_pct(row['ci_low'])}–{_pct(row['ci_high'])}"


def _md_rate_table(t: pd.DataFrame, column: str) -> str:
    lines = [f"| {column} | Customers | Churned | Churn rate | 95% CI |", "|---|---:|---:|---:|---:|"]
    for _, r in t.iterrows():
        lines.append(f"| {r[column]} | {r['customers']:,} | {r['churned']:,} | {_pct(r['churn_rate'])} | {_ci(r)} |")
    return "\n".join(lines)


def _extremes_sentence(t: pd.DataFrame, column: str) -> str:
    hi = t.loc[t["churn_rate"].idxmax()]
    lo = t.loc[t["churn_rate"].idxmin()]
    ratio = hi["churn_rate"] / lo["churn_rate"]
    overlap = hi["ci_low"] <= lo["ci_high"]
    return (
        f"Highest: **{hi[column]}** at {_pct(hi['churn_rate'])} (95% CI {_ci(hi)}, n={hi['customers']:,}). "
        f"Lowest: **{lo[column]}** at {_pct(lo['churn_rate'])} (95% CI {_ci(lo)}, n={lo['customers']:,}). "
        f"Ratio highest/lowest: {ratio:.1f}x. "
        + ("The confidence intervals overlap, so this gap may be noise."
           if overlap else "The confidence intervals do not overlap.")
    )


def _contract_internet_sentence(seg: pd.DataFrame) -> str:
    rate = seg.pivot(index="Contract", columns="InternetService", values="churn_rate")
    fiber_higher = [c for c in rate.index if rate.loc[c, "Fiber optic"] > rate.loc[c, "DSL"]]
    m2m_higher = [i for i in rate.columns if rate.loc["Month-to-month", i] > rate[i].drop("Month-to-month").max()]
    parts = []
    if len(fiber_higher) == len(rate.index):
        detail = "; ".join(f"{c}: {_pct(rate.loc[c, 'Fiber optic'])} vs {_pct(rate.loc[c, 'DSL'])}" for c in rate.index)
        parts.append(f"Fiber optic churn exceeds DSL churn **within every contract type** ({detail}).")
    else:
        parts.append(f"Fiber optic churn exceeds DSL churn only for: {', '.join(fiber_higher) or 'none'}.")
    if len(m2m_higher) == len(rate.columns):
        parts.append("Month-to-month churn is the highest contract rate **within every internet-service group**.")
    parts.append(
        "Because each pattern persists after splitting by the other factor, neither one is simply a "
        "proxy for the other. This is still not evidence of causation: other variables (price, tenure, "
        "payment method) also differ between these groups."
    )
    return " ".join(parts)


def write_findings(r: dict, path) -> None:
    t, q, d = r["target"], r["quality"], r["duplicates"]
    tables = r["tables"]
    num = r["numeric_summary"].set_index(["column", "group"])
    corr = r["correlations"]
    charges = tables["monthly_charges_band"]
    sql_passed = sum(c["passed"] for c in r["sql_checks"])

    def med(col, group):
        return num.loc[(col, group), "median"]

    lines = [
        "# Phase 2 findings: EDA and SQL insights",
        "",
        f"_Generated by `python -m churn_platform.eda` from `{r['file']}` "
        f"(SHA-256 `{r['sha256'][:16]}…`). Do not edit by hand; re-run the script._",
        "",
        "**All findings are descriptive associations in one observational snapshot. "
        "None of them shows that changing a factor would change churn.**",
        "",
        "## 1. Target variable",
        "",
        f"- {t['customers']:,} customers: **{t['churned']:,} churned ({_pct(t['churn_rate'])})**, "
        f"{t['retained']:,} retained ({_pct(t['retention_rate'])}).",
        f"- The classes are imbalanced. A model that always predicts \"No churn\" would be "
        f"{_pct(t['retention_rate'])} accurate and useless, so accuracy alone will not be used to judge models.",
        "",
        "![Churn distribution](figures/churn_distribution.png)",
        "",
        "## 2. Data quality",
        "",
        "- All 21 raw columns are read as text. For analysis, `tenure` becomes an integer and "
        "`MonthlyCharges` / `TotalCharges` become floats.",
        f"- `TotalCharges` has **{q['total_charges_blank_rows']} blank values** (a single space). They become "
        "NaN, **not 0**, and a `TotalCharges_blank` flag records them. "
        + ("All of them have `tenure = 0`." if q["total_charges_blank_all_tenure_zero"] else
           "**Not all of them have tenure 0; investigate.**")
        + f" There are {q['tenure_zero_rows']} tenure-0 customers in total. The raw CSV is unchanged.",
        f"- Duplicate customer IDs: {q['duplicate_customer_ids']}. Fully identical rows: {q['fully_duplicated_rows']}.",
        f"- **Duplicate feature profiles:** {d['rows']} customers ({_pct(d['share_of_dataset'])}) fall into "
        f"{d['groups']} groups that share every feature value but have different IDs (largest group: {d['largest_group']}). "
        f"**{d['conflicting_groups']} groups ({d['rows_in_conflicting_groups']} customers) contain both churners and "
        "non-churners.** The features cannot tell those customers apart, so no model can classify all of them correctly. "
        f"Tenure values in these rows: {d['tenure_values_in_duplicated_rows']}"
        + (". All of them are one-month customers, where TotalCharges equals one month's bill and profiles "
           "easily collide." if d["tenure_values_in_duplicated_rows"] == [1] else ".")
        + " Nothing was removed; see `tables/duplicate_profiles.csv`.",
        "- `customerID` is treated purely as an identifier and is excluded from every analysis grouping.",
        "",
        "## 3. Numeric distributions",
        "",
        "| Column | Median (churned) | Median (retained) | Skew (all) |",
        "|---|---:|---:|---:|",
    ]
    for col in ["tenure", "MonthlyCharges", "TotalCharges"]:
        lines.append(f"| {col} | {med(col, 'churned'):,.2f} | {med(col, 'retained'):,.2f} | {num.loc[(col, 'all'), 'skew']:.2f} |")
    lines += [
        "",
        f"- Churned customers have shorter tenure (median {med('tenure', 'churned'):.0f} vs "
        f"{med('tenure', 'retained'):.0f} months) and higher monthly charges (median "
        f"${med('MonthlyCharges', 'churned'):.2f} vs ${med('MonthlyCharges', 'retained'):.2f}).",
        f"- Their lower `TotalCharges` (median ${med('TotalCharges', 'churned'):,.2f} vs "
        f"${med('TotalCharges', 'retained'):,.2f}) follows from shorter tenure: "
        f"corr(tenure, TotalCharges) = {corr.loc['tenure', 'TotalCharges']:.3f} and "
        f"corr(MonthlyCharges, TotalCharges) = {corr.loc['MonthlyCharges', 'TotalCharges']:.3f}. "
        "TotalCharges / (tenure × MonthlyCharges) has median "
        f"{q['total_charges_ratio_to_tenure_x_monthly']['median']} (5th–95th percentile "
        f"{q['total_charges_ratio_to_tenure_x_monthly']['p05']}–{q['total_charges_ratio_to_tenure_x_monthly']['p95']}), "
        "so TotalCharges is close to tenure × MonthlyCharges and adds little independent information "
        "(a collinearity issue for Phase 3).",
        f"- Point-biserial correlation with churn: tenure {corr.loc['tenure', 'churned']:.3f}, "
        f"MonthlyCharges {corr.loc['MonthlyCharges', 'churned']:.3f}, "
        f"TotalCharges {corr.loc['TotalCharges', 'churned']:.3f}. Correlation only measures linear association.",
        "- **Caution about tenure:** for churned customers, tenure is how long they stayed *before leaving*. "
        "For retained customers it is still growing. Part of the tenure–churn gap is built into how the snapshot "
        "was taken, not just customer behaviour.",
        "",
        "![Numeric distributions](figures/numeric_distributions.png)",
        "",
        "## 4. Churn by segment",
        "",
    ]
    sections = [
        ("contract", "Contract", "Contract type", "churn_by_contract.png"),
        ("tenure_group", "tenure_group", "Tenure group (months)", "churn_by_tenure_group.png"),
        ("payment_method", "PaymentMethod", "Payment method", "churn_by_payment_method.png"),
        ("internet_service", "InternetService", "Internet service", "churn_by_internet_service.png"),
        ("monthly_charges_band", "monthly_charges_band", "Monthly charges band ($)", "churn_by_monthly_charges_band.png"),
        ("senior_citizen", "SeniorCitizen", "Senior citizen (0 = no, 1 = yes)", "churn_by_senior_citizen.png"),
    ]
    for key, column, heading, fig in sections:
        lines += [f"### {heading}", "", _md_rate_table(tables[key], column), "",
                  _extremes_sentence(tables[key], column), "", f"![{heading}](figures/{fig})", ""]

    rates = charges.set_index("monthly_charges_band")["churn_rate"]
    monotonic = rates.is_monotonic_increasing
    lines += [
        "**Monthly charges:** churn "
        + ("rises steadily across the bands." if monotonic else
           f"does **not** rise steadily with price. The 90+ band ({_pct(rates['90+'])}) is below the 70-90 band "
           f"({_pct(rates['70-90'])}). The relationship is not a simple \"higher price, more churn\" pattern; "
           "the reason is not established by this analysis."),
        "",
        "Every other categorical feature is shown in `figures/churn_by_all_categorical_features.png` "
        "and `tables/categorical_churn_rates.csv`.",
        "",
        "![All categorical features](figures/churn_by_all_categorical_features.png)",
        "",
        "## 5. Interaction: contract × internet service",
        "",
        "| Contract | Internet | Customers | % of customers | Churn rate | 95% CI |",
        "|---|---|---:|---:|---:|---:|",
    ]
    for _, row in tables["contract_internet"].iterrows():
        lines.append(f"| {row['Contract']} | {row['InternetService']} | {row['customers']:,} | "
                     f"{_pct(row['share_of_customers'])} | {_pct(row['churn_rate'])} | {_ci(row)} |")
    top = tables["contract_internet"].iloc[0]
    lines += [
        "",
        f"The highest-churn segment is **{top['Contract']} + {top['InternetService']}**: "
        f"{_pct(top['churn_rate'])} churn among {top['customers']:,} customers "
        f"({_pct(top['share_of_customers'])} of all customers, {top['churned']:,} of the "
        f"{t['churned']:,} churners = {_pct(top['churned'] / t['churned'])}).",
        "",
        _contract_internet_sentence(tables["contract_internet"]),
        "",
        "![Contract × internet heatmap](figures/churn_by_contract_and_internet.png)",
        "",
        "## 6. SQL vs Python consistency",
        "",
        f"The SQLite view (`sql/create_analysis_view.sql`) does its own type conversion and grouping, "
        f"independently of pandas. **{sql_passed}/{len(r['sql_checks'])} queries match the pandas results** "
        "(counts exactly; rates to the 4 decimal places SQL rounds to).",
        "",
        "| Query | Rows | Match |",
        "|---|---:|---|",
    ]
    for c in r["sql_checks"]:
        lines.append(f"| `{c['query']}` | {c['rows']} | {'yes' if c['passed'] else 'NO: ' + '; '.join(c['problems'])} |")
    lines += [
        "",
        "## 7. Limitations: what this analysis does NOT show",
        "",
        "- **Association, not causation.** Moving a customer to a two-year contract will not necessarily "
        "cut their churn risk to the two-year rate. Customers *choose* contracts, and the people who commit "
        "for two years probably differ in ways the data does not record.",
        "- **Confounding.** Contract, tenure, internet service, price and payment method are related to each "
        "other. A one-variable table blends their effects together.",
        "- **One snapshot, no dates.** We can't tell when customers churned, follow anyone over time, or "
        "tell voluntary from involuntary churn.",
        "- **Synthetic data.** IBM created this dataset for demos. Patterns may not hold for a real business.",
        "- **Confidence intervals** reflect sampling noise only and assume customers are independent. "
        "They do not cover bias or confounding.",
        "- **Band boundaries** (tenure groups, charge bands) are round numbers chosen for readability. "
        "Different cut-offs would give somewhat different tables.",
        "",
        "## 8. Implications for Phase 3 (noted, not yet acted on)",
        "",
        f"- Stratify the train/test split on `Churn` to keep the {_pct(t['churn_rate'])} rate in both sets.",
        "- Decide how to handle the 11 blank `TotalCharges` values inside a training-only pipeline. "
        "Filling them with 0 is defensible since tenure = 0; dropping the column is also an option given "
        "its collinearity with tenure.",
        "- Exclude `customerID` from the features.",
        f"- Expect label noise: {d['rows_in_conflicting_groups']} customers have identical profiles with mixed outcomes.",
        "- Use precision, recall, F1, ROC-AUC and PR-AUC rather than accuracy.",
        "",
    ]
    path.write_text("\n".join(lines), encoding="utf-8")
